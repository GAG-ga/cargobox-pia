"""Interfaces de repositorio (el dominio define el contrato; infraestructura lo implementa)."""
from typing import Protocol

from src.domain.estados import EstadoGuia
from src.domain.guia import Guia
from src.domain.incidencia import Incidencia, TipoIncidencia
from src.domain.value_objects import NumeroGuia


class GuiaRepository(Protocol):
    def siguiente_numero(self) -> NumeroGuia: ...
    def por_numero(self, numero: str) -> Guia | None: ...
    def guardar(self, guia: Guia) -> None: ...
    def en_estados(self, estados: set[EstadoGuia]) -> list[Guia]: ...


class IncidenciaRepository(Protocol):
    def siguiente_folio(self) -> str: ...
    def por_folio(self, folio: str) -> Incidencia | None: ...
    def guardar(self, incidencia: Incidencia) -> None: ...
    def abiertas(self, tipo: TipoIncidencia | None = None) -> list[Incidencia]: ...
    def pendientes(self) -> list[Incidencia]: ...
